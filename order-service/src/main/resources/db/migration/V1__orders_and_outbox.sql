-- Adopt the orders table created by the original Hibernate configuration if it exists.
CREATE TABLE IF NOT EXISTS orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product VARCHAR(255) NOT NULL,
    price NUMERIC NOT NULL
);

ALTER TABLE orders ALTER COLUMN price TYPE NUMERIC USING price::text::numeric;
ALTER TABLE orders ADD COLUMN idempotency_key VARCHAR(128);
ALTER TABLE orders ADD CONSTRAINT orders_checkout_fields CHECK (
    idempotency_key IS NULL OR (
        product IS NOT NULL AND char_length(product) > 0 AND
        price IS NOT NULL AND price BETWEEN 0.01 AND 9999999999.99 AND price = round(price, 2)
    )
);
CREATE UNIQUE INDEX orders_idempotency_key ON orders (idempotency_key);

CREATE TABLE order_outbox (
    event_id UUID PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id),
    payload TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    attempts INTEGER NOT NULL DEFAULT 0
);

CREATE INDEX order_outbox_due ON order_outbox (next_attempt_at, created_at);
